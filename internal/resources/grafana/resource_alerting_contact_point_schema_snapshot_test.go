// TestContactPointSchemaSnapshot renders the schema of grafana_contact_point as text and compares it
// with testdata/contact_point_schema.golden, in the same format as the receiver resource's snapshot
// so the two can be compared. When it differs, the test rewrites the golden file and fails; review
// the diff and run the test again.
func TestContactPointSchemaSnapshot(t *testing.T) {
	var lines []snapshotLine

	// Top-level attributes that are not integrations.
	integrationFields := map[string]struct{}{}
	for _, n := range notifiers {
		integrationFields[n.meta().field] = struct{}{}
	}
	for name, sch := range resourceContactPoint().Schema.Schema {
		if _, ok := integrationFields[name]; !ok {
			lines = append(lines, snapshotLine{name, sdkTypeName(sch) + sdkFlags(sch)})
		}
	}

	for _, n := range notifiers {
		meta := n.meta()
		blockSchema := resourceContactPoint().Schema.Schema[meta.field]
		path := meta.field + "{set}[]"
		lines = append(lines, snapshotLine{path, "block(set)" + sdkFlags(blockSchema) + ", grafana type=" + meta.typeStr})
		dumpSDKFields(&lines, path, "", "", n.schema().Schema, meta.fieldMapper)
	}

	sort.Slice(lines, func(i, j int) bool { return lines[i].path < lines[j].path })
	var b strings.Builder
	b.WriteString("# Terraform schema of grafana_contact_point. Regenerated by TestContactPointSchemaSnapshot.\n" +
		"#\n" +
		"# Each line is: <terraform path>: <type and flags>, grafana=<Grafana settings key>.\n" +
		"# Integration blocks list the Grafana integration type as type=<type>. Nested keys are dot-separated.\n")
	for _, l := range lines {
		b.WriteString(l.path + ": " + l.text + "\n")
	}
	got := b.String()

	path := filepath.Join("testdata", "contact_point_schema.golden")
	want, err := os.ReadFile(path)
	if err == nil && string(want) == got {
		return
	}
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	require.NoError(t, os.WriteFile(path, []byte(got), 0o600))
	t.Fatalf("%s was out of date and has been rewritten; review the diff and run the test again", path)
}

type snapshotLine struct{ path, text string }

// dumpSDKFields walks an integration's schema. tfKey is the dot-separated Terraform key used to look
// up field mappers; gfKey is the dot-separated Grafana settings key the field is stored under.
func dumpSDKFields(lines *[]snapshotLine, linePrefix, tfKey, gfKey string, s map[string]*schema.Schema, mappers map[string]fieldMapper) {
	for name, sch := range s {
		fullTF := name
		if tfKey != "" {
			fullTF = tfKey + "." + name
		}

		key := name
		if m := mappers[fullTF]; m.newKey != "" {
			key = m.newKey
		}
		fullGF := key
		if gfKey != "" {
			fullGF = gfKey + "." + key
		}

		var grafana string
		switch {
		case tfKey == "" && name == "uid":
			grafana = "uid (integration field)"
		case tfKey == "" && name == "disable_resolve_message":
			grafana = "disableResolveMessage (integration field)"
		case tfKey == "" && name == "settings":
			grafana = "(extra settings, merged into the settings)"
		default:
			grafana = fullGF
		}

		if res, ok := sch.Elem.(*schema.Resource); ok {
			path := linePrefix + "." + name + "{set}"
			if sch.Type == schema.TypeList {
				path = linePrefix + "." + name + "[]"
			}
			*lines = append(*lines, snapshotLine{path, strings.ToLower(sch.Type.String()) + sdkFlags(sch) + ", grafana=" + grafana})
			dumpSDKFields(lines, path, fullTF, fullGF, res.Schema, mappers)
			continue
		}
		*lines = append(*lines, snapshotLine{linePrefix + "." + name, sdkTypeName(sch) + sdkFlags(sch) + ", grafana=" + grafana})
	}
}

func sdkTypeName(s *schema.Schema) string {
	elem := func() string {
		if e, ok := s.Elem.(*schema.Schema); ok {
			return sdkTypeName(e)
		}
		return "string"
	}
	switch s.Type {
	case schema.TypeString:
		return "string"
	case schema.TypeBool:
		return "bool"
	case schema.TypeInt:
		return "int64"
	case schema.TypeFloat:
		return "float64"
	case schema.TypeList, schema.TypeSet:
		return strings.ToLower(s.Type.String()) + "(" + elem() + ")"
	case schema.TypeMap:
		return "map(" + elem() + ")"
	}
	return s.Type.String()
}

func sdkFlags(s *schema.Schema) string {
	var parts []string
	switch {
	case s.Required:
		parts = append(parts, "required")
	case s.Optional:
		parts = append(parts, "optional")
	}
	if s.Computed {
		parts = append(parts, "computed")
	}
	if s.Sensitive {
		parts = append(parts, "sensitive")
	}
	if s.Default != nil {
		parts = append(parts, fmt.Sprintf("default=%v", s.Default))
	}
	if s.ForceNew {
		parts = append(parts, "forcenew")
	}
	if s.MaxItems > 0 {
		parts = append(parts, fmt.Sprintf("maxitems=%d", s.MaxItems))
	}
	if len(parts) == 0 {
		return ""
	}
	return ", " + strings.Join(parts, ", ")
}
