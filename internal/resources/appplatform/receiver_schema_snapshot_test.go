// TestReceiverSchemaSnapshot renders the spec schema of the receiver resource as text and compares
// it with testdata/receiver_schema.golden, so changes to the integration schema snapshot show up as
// a reviewable diff of the Terraform schema. When it differs, the test rewrites the golden file and
// fails; review the diff and run the test again.
func TestReceiverSchemaSnapshot(t *testing.T) {
	var resp resource.SchemaResponse
	Receiver().Resource.Schema(context.Background(), resource.SchemaRequest{}, &resp)
	require.False(t, resp.Diagnostics.HasError(), "%v", resp.Diagnostics)

	spec, ok := resp.Schema.Blocks["spec"].(schema.SingleNestedBlock)
	require.True(t, ok)

	def, _, err := newReceiverDefinition()
	require.NoError(t, err)
	grafana := receiverGrafanaKeys(def)

	var lines []snapshotLine
	dumpFrameworkSchema(context.Background(), &lines, "spec", spec.Attributes, spec.Blocks, grafana)

	header := "# Terraform schema of grafana_apps_notifications_receiver_v1beta1 (spec), derived from\n" +
		"# integrationschemas/integration-schemas.json. Regenerated by TestReceiverSchemaSnapshot.\n" +
		"#\n" +
		"# Each line is: <terraform path>: <type and flags>, grafana=<Grafana settings key>.\n" +
		"# Integration blocks list the Grafana integration type as type=<type>. Nested keys are dot-separated.\n"
	assertGolden(t, filepath.Join("testdata", "receiver_schema.golden"), header+renderSnapshotLines(lines))
}

// snapshotLine is one line of a schema snapshot, sorted by path so a block precedes its children.
type snapshotLine struct{ path, text string }

func renderSnapshotLines(lines []snapshotLine) string {
	sort.Slice(lines, func(i, j int) bool { return lines[i].path < lines[j].path })
	var b strings.Builder
	for _, l := range lines {
		b.WriteString(l.path + ": " + l.text + "\n")
	}
	return b.String()
}

// receiverGrafanaKeys maps the Terraform path of every integration field to the Grafana settings
// key it is stored under (dot-separated for nested settings), and each integration block to its type.
func receiverGrafanaKeys(def *receiverDefinition) map[string]string {
	keys := map[string]string{}
	var walk func(prefix string, fields []*integrationschemas.Field)
	walk = func(prefix string, fields []*integrationschemas.Field) {
		for _, f := range fields {
			p := prefix + "." + f.TFName
			switch f.Kind {
			case integrationschemas.KindObject:
				p += "{}"
			case integrationschemas.KindObjectList:
				p += "[]"
			}
			keys[p] = strings.Join(f.Path, ".")
			walk(p, f.Children)
		}
	}
	for _, it := range def.types {
		block := "spec." + it.TFName + "[]"
		keys[block] = "type=" + it.APIType + " version=" + it.Version
		keys[block+"."+receiverIntegrationUID] = "uid (integration field)"
		keys[block+"."+receiverIntegrationDisableResolveMessage] = "disableResolveMessage (integration field)"
		walk(block, it.Fields)
	}
	return keys
}

// assertGolden compares got with the golden file. On a difference, or if the file is missing, it
// writes got to the file and fails the test.
func assertGolden(t *testing.T, path, got string) {
	t.Helper()
	want, err := os.ReadFile(path)
	if err == nil && string(want) == got {
		return
	}
	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o755))
	require.NoError(t, os.WriteFile(path, []byte(got), 0o600))
	t.Fatalf("%s was out of date and has been rewritten; review the diff and run the test again", path)
}

func dumpFrameworkSchema(ctx context.Context, lines *[]snapshotLine, prefix string, attrs map[string]schema.Attribute, blocks map[string]schema.Block, grafana map[string]string) {
	withKey := func(path, text string) snapshotLine {
		if k, ok := grafana[path]; ok {
			if strings.HasPrefix(k, "type=") {
				text += ", grafana " + k
			} else {
				text += ", grafana=" + k
			}
		}
		return snapshotLine{path, text}
	}
	for name, a := range attrs {
		p := prefix + "." + name
		*lines = append(*lines, withKey(p, describeFrameworkAttribute(ctx, a)))
	}
	for name, b := range blocks {
		switch b := b.(type) {
		case schema.ListNestedBlock:
			p := fmt.Sprintf("%s.%s[]", prefix, name)
			*lines = append(*lines, withKey(p, "block(list)"))
			dumpFrameworkSchema(ctx, lines, p, b.NestedObject.Attributes, b.NestedObject.Blocks, grafana)
		case schema.SingleNestedBlock:
			p := fmt.Sprintf("%s.%s{}", prefix, name)
			*lines = append(*lines, withKey(p, "block"))
			dumpFrameworkSchema(ctx, lines, p, b.Attributes, b.Blocks, grafana)
		default:
			*lines = append(*lines, snapshotLine{prefix + "." + name, fmt.Sprintf("unsupported block %T", b)})
		}
	}
}

func describeFrameworkAttribute(ctx context.Context, a schema.Attribute) string {
	parts := []string{frameworkTypeName(a.GetType())}
	switch {
	case a.IsRequired():
		parts = append(parts, "required")
	case a.IsOptional():
		parts = append(parts, "optional")
	}
	if a.IsComputed() {
		parts = append(parts, "computed")
	}
	if a.IsSensitive() {
		parts = append(parts, "sensitive")
	}

	var validators []string
	describe := func(vs []validator.String) {
		for _, v := range vs {
			validators = append(validators, v.Description(ctx))
		}
	}
	describeInt := func(vs []validator.Int64) {
		for _, v := range vs {
			validators = append(validators, v.Description(ctx))
		}
	}
	switch a := a.(type) {
	case schema.StringAttribute:
		describe(a.Validators)
		if a.Default != nil {
			parts = append(parts, "default="+a.Default.Description(ctx))
		}
	case schema.Int64Attribute:
		describeInt(a.Validators)
	case schema.BoolAttribute:
		if a.Default != nil {
			parts = append(parts, "default="+a.Default.Description(ctx))
		}
	}
	if len(validators) > 0 {
		parts = append(parts, "validators=["+strings.Join(validators, "; ")+"]")
	}
	return strings.Join(parts, ", ")
}

func frameworkTypeName(t attr.Type) string {
	switch t := t.(type) {
	case basetypes.StringType:
		return "string"
	case basetypes.BoolType:
		return "bool"
	case basetypes.Int64Type:
		return "int64"
	case basetypes.ListType:
		return "list(" + frameworkTypeName(t.ElemType) + ")"
	case basetypes.MapType:
		return "map(" + frameworkTypeName(t.ElemType) + ")"
	}
	return fmt.Sprintf("%T", t)
}
